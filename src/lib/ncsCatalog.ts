export function searchNcsMusic(query: string): NcsTrack[] {
  const q = (query || '').toLowerCase().trim();
  if (!q) return NCS_CATALOG;
  return NCS_CATALOG.filter(
    (t) =>
      t.title.toLowerCase().includes(q) ||
      t.artist.toLowerCase().includes(q) ||
      (t.genre && t.genre.toLowerCase().includes(q))
  );
}

export function getNcsTrackById(id: string): NcsTrack | undefined {
  return NCS_CATALOG.find((t) => t.id === id);
}
